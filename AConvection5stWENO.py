import jax.numpy as jnp
from jax import jit
eta=1E-6

@jit
def wigtht(segma1,segma2,segma3):
    W1ba=1/(10*((eta+segma1)**2))
    W2ba=3/(5 *((eta+segma2)**2))
    W3ba=3/(10*((eta+segma3)**2))
    sumW=W1ba+W2ba+W3ba
    W1=W1ba/sumW
    W2=W2ba/sumW
    W3=W3ba/sumW
    return W1,W2,W3


